import dotenv from "dotenv";
dotenv.config();
import { generateGeminiContent } from "../utils/geminiHelper.js";

export const handleChat = async (req, res) => {
  const { message } = req.body;

  if (!message || !message.trim()) {
    return res.status(400).json({ success: false, message: "Message is required" });
  }

  if (!process.env.GEMINI_API_KEY) {
    return res.status(200).json({
      success: true,
      reply: `
        <div class="bot-card">
          <h4>🔒 SafeNet AI Security Agent</h4>
          <p>Gemini API key is currently not configured in the backend environment. Please verify your <code>GEMINI_API_KEY</code>.</p>
        </div>
      `,
    });
  }

  try {
    const systemInstruction = `
You are SafeNet Sentinel, an elite AI Cybersecurity Specialist and Incident Response Agent.
Provide helpful, technically accurate, and structured advice for the user's cybersecurity query.

Guidelines:
1. Include actionable mitigation steps and code snippets where relevant.
2. Structure your output clearly:
   - 🛡️ **Overview & Threat Summary**
   - 🧠 **Technical Deep-Dive**
   - 🛠️ **Remediation & Best Practices**
   - 💡 **Pro-Tip / Prevention Rule**
3. Ensure formatting is clean, crisp HTML/Markdown.
`;

    const result = await generateGeminiContent(
      `${systemInstruction}\n\nUser Question: ${message}`,
      { model: process.env.GEMINI_MODEL || "gemini-3.6-flash" }
    );

    let rawReply = result.text || "No response generated by AI.";
    const formattedReply = formatAIResponse(rawReply);

    return res.status(200).json({
      success: true,
      reply: formattedReply,
      modelUsed: result.modelUsed,
    });
  } catch (error) {
    console.error("Chatbot Gemini error:", error.message);
    return res.status(500).json({
      success: false,
      message: "Error fetching response from AI assistant",
      details: error.message,
    });
  }
};

function formatAIResponse(text) {
  if (!text || typeof text !== "string") return "<p>No response from AI.</p>";

  // Strip code fences if whole response wrapped
  let cleaned = text.replace(/^```(?:html|markdown)?\s*/i, "").replace(/\s*```$/i, "").trim();

  // Basic HTML styling conversions for common markdown patterns
  cleaned = cleaned
    .replace(/^### (.*$)/gim, '<h4 class="ai-heading">$1</h4>')
    .replace(/^## (.*$)/gim, '<h3 class="ai-heading-lg">$1</h3>')
    .replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")
    .replace(/`([^`]+)`/g, '<code class="ai-code">$1</code>')
    .replace(/(?:^|\n)[-–*]\s+(.*)/g, '<li class="ai-bullet">$1</li>')
    .replace(/\n\n+/g, "</p><p>");

  return `
    <div class="ai-response-container">
      <p>${cleaned}</p>
    </div>
  `;
}
